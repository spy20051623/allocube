import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { startRealtimeFixture } from "./test-realtime-http.mjs";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const fixture = await startRealtimeFixture();
let browser;
try {
  const day = new Date(Date.now() + 3 * 86400_000 + 8 * 3600_000).toISOString().slice(0, 10);
  const boundary = new Date(Date.parse(`${day}T00:00:00+08:00`) + 86400_000).toISOString();
  const members = await fixture.request("Administrator", `/admin/machines/${fixture.ids.machine1}/access`);
  const owner = members.body.members.find(member => member.id === fixture.ids.owner);
  const updated = await fixture.request("Administrator", `/admin/machines/${fixture.ids.machine1}/members/${fixture.ids.owner}/expiry`, "PATCH", { expiresAt: boundary, expectedVersion: owner.expectedVersion });
  assert.equal(updated.status, 200, JSON.stringify(updated.body));
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
  await mkdir(".codex-tmp/calendar-access-expiry", { recursive: true });
  for (const [timezoneId, theme] of [["America/New_York", "light"], ["Pacific/Honolulu", "dark"]]) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId });
    await context.addInitScript(theme => {
      localStorage.setItem("allocube:locale:v1", "zh-CN");
      localStorage.setItem("allocube:theme:v1", theme);
      localStorage.setItem("allocube.calendar-preference.v1", JSON.stringify({ visibleHours: 24, zoomPreferenceVersion: 1, reservationMode: "RESOURCE_GROUP" }));
    }, theme);
    const cookie = fixture.accounts.owner.cookie, split = cookie.indexOf("=");
    await context.addCookies([{ name: cookie.slice(0, split), value: cookie.slice(split + 1), url: fixture.origin }]);
    const page = await context.newPage(); page.setDefaultTimeout(12000);
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto(`${fixture.origin}/calendar?date=${day}&view=day`);
    await page.locator(".live-state.connected").waitFor();
    assert.equal(await page.locator(".machine-strip-expiry").count(), 0);
    const shade = page.locator(".time-track .access-expiry-shade");
    await shade.waitFor();
    const renewButton = shade.getByRole("button", { name: "延期", exact: true });
    await renewButton.click();
    const renewalModal = page.locator(".machine-access-modal");
    await renewalModal.waitFor();
    const renewalDate = new Date(Date.parse(`${day}T00:00:00Z`) + 30 * 86400_000).toISOString().slice(0, 10);
    assert.equal(await renewalModal.getByRole("button", { name: "延期至", exact: true }).innerText(), renewalDate);
    assert.equal(await page.locator(".draft-card").count(), 0, "Renewal click must not start a reservation drag");
    await page.screenshot({ path: `.codex-tmp/calendar-access-expiry/${theme}-renewal.png`, fullPage: true });
    await renewalModal.getByRole("button", { name: "取消", exact: true }).click();
    const expiryPattern = await shade.evaluate(element => getComputedStyle(element).backgroundImage);
    assert.equal(await shade.evaluate(element => getComputedStyle(element).zIndex), "1", "Expiry shading must use the same layer as past time");
    const localBoundary = await page.evaluate(iso => {
      const d = new Date(iso);
      return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}T${String(d.getHours()).padStart(2,'0')}:${String(d.getMinutes()).padStart(2,'0')}`;
    }, boundary);
    const localHour = Number(localBoundary.slice(11, 13));
    assert(Math.abs(await shade.evaluate(element => parseFloat(element.style.left)) - localHour / 24 * 100) < .01);
    await page.screenshot({ path: `.codex-tmp/calendar-access-expiry/${theme}-day.png`, fullPage: true });
    // A drag that begins beyond the boundary must not create a draft.
    const track = page.locator(".time-track").first();
    const bounds = await track.boundingBox();
    await page.mouse.move(bounds.x + bounds.width * .8, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width * .9, bounds.y + bounds.height / 2, { steps: 8 });
    await page.mouse.up();
    assert.equal(await page.locator(".draft-card").count(), 0);
    await page.mouse.move(bounds.x + bounds.width * (localHour - 1) / 24, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width * (localHour + 1) / 24, bounds.y + bounds.height / 2, { steps: 8 });
    await page.mouse.up();
    await page.locator(".draft-card").waitFor();
    assert.equal(await page.locator('.draft-card [name="endAt"]').inputValue(), localBoundary, "Crossing drag ends exactly at the access boundary");
    await page.locator(".draft-card").getByRole("button", { name: "删除 CPU group 1 草稿", exact: true }).click();
    await page.locator(".drawer-add-button").click();
    const dialog = page.getByRole("dialog");
    const start = dialog.locator('[name="manualStartAt"]'), end = dialog.locator('[name="manualEndAt"]');
    assert.equal(await end.getAttribute("max"), localBoundary);
    await start.fill(`${day}T01:00`);
    await end.fill(`${day}T23:00`);
    await dialog.getByText("所选时间超出机器使用期限", { exact: true }).waitFor();
    await dialog.getByRole("button", { name: "加入占用详情", exact: true }).click();
    assert.equal(await page.locator(".draft-card").count(), 0);
    await end.fill(localBoundary);
    await dialog.getByRole("button", { name: "加入占用详情", exact: true }).click();
    await page.locator(".draft-card").waitFor();
    assert.equal(await page.locator('.draft-card [name="endAt"]').inputValue(), localBoundary);
    await page.getByRole("button", { name: "当地", exact: true }).click();
    assert.equal(await page.locator(".machine-strip-expiry").count(), 0);
    await page.getByRole("button", { name: "北京", exact: true }).click();
    await page.getByRole("button", { name: "一周", exact: true }).click();
    assert.equal(await page.locator(".week-day-cell .access-expiry-shade").count(), 0);
    assert.equal(await page.locator(".week-day-cell .calendar-expiry-renew").count(), 0);
    assert.equal(await page.locator(".week-day-cell").getByText("使用权已到期", { exact: true }).count(), 0);
    await page.screenshot({ path: `.codex-tmp/calendar-access-expiry/${theme}-week.png`, fullPage: true });
    await page.getByRole("button", { name: "一天", exact: true }).click();
    const dayUrl = page.url();
    const draftCount = await page.locator(".draft-card").count();
    await page.locator(".time-track .calendar-expiry-renew:visible").first().focus();
    await page.keyboard.press("Enter");
    await renewalModal.waitFor();
    assert.equal(page.url(), dayUrl, "Renewal must not navigate away from the day view");
    await renewalModal.getByRole("button", { name: "提交申请", exact: true }).click();
    await renewalModal.waitFor({ state: "hidden" });
    await page.locator(".calendar-expiry-pending:visible").first().waitFor();
    assert.equal(await page.locator(".draft-card").count(), draftCount);
    const catalog = await fixture.request("owner", "/machines/catalog");
    const requestedMachine = catalog.body.machines.find(machine => machine.id === fixture.ids.machine1);
    assert.equal(requestedMachine.expiresAt, boundary, "Applying must preserve the current authorization");
    assert.equal(requestedMachine.request.previousExpiresAt, boundary);
    await page.screenshot({ path: `.codex-tmp/calendar-access-expiry/${theme}-pending.png`, fullPage: true });
    await fixture.request("owner", `/machine-access/requests/${requestedMachine.request.id}`, "DELETE");
    await page.locator(".time-track .calendar-expiry-renew:visible").first().waitFor();
    // Compare shared disabled backgrounds without changing the fixture's permissions.
    await page.route("**/api/v1/timeline?**", async route => {
      const response = await route.fetch();
      const payload = await response.json();
      payload.machines.find(machine => machine.id === fixture.ids.machine2).status = "DISABLED";
      await route.fulfill({ response, json: payload });
    });
    const yesterday = new Date(Date.now() - 2 * 86400_000).toISOString().slice(0, 10);
    await page.goto(`${fixture.origin}/calendar?date=${yesterday}&view=day`);
    const pastShade = page.locator(".past-time-shade").first();
    const disabledShade = page.locator(".calendar-blocked-time--disabled");
    await disabledShade.waitFor();
    assert.equal(await pastShade.evaluate(element => getComputedStyle(element).backgroundImage), expiryPattern);
    assert.equal(await disabledShade.evaluate(element => getComputedStyle(element).backgroundImage), expiryPattern);
    assert.equal(await disabledShade.innerText(), "机器已停用");
    assert.equal(await pastShade.evaluate(element => element.style.width), "100%");
    await page.screenshot({ path: `.codex-tmp/calendar-access-expiry/${theme}-shared-disabled.png`, fullPage: true });
    assert.deepEqual(errors, []);
    await context.close();
  }
  const mobile = await browser.newContext({ viewport: { width: 390, height: 900 }, timezoneId: "America/New_York" });
  await mobile.addInitScript(() => {
    localStorage.setItem("allocube:locale:v1", "en");
    localStorage.setItem("allocube.calendar-preference.v1", JSON.stringify({ visibleHours: 24, zoomPreferenceVersion: 1 }));
  });
  const cookie = fixture.accounts.owner.cookie, split = cookie.indexOf("=");
  await mobile.addCookies([{ name: cookie.slice(0, split), value: cookie.slice(split + 1), url: fixture.origin }]);
  const mobilePage = await mobile.newPage();
  await mobilePage.goto(`${fixture.origin}/calendar?date=${day}&view=day`);
  const mobileRenew = mobilePage.locator(".calendar-expiry-renew:visible").first();
  await mobileRenew.click();
  await mobilePage.locator(".machine-access-modal").waitFor();
  await mobilePage.screenshot({ path: ".codex-tmp/calendar-access-expiry/mobile-en-renewal.png", fullPage: true });
  await mobilePage.locator(".machine-access-modal").getByRole("button", { name: "Cancel", exact: true }).click();
  await mobilePage.screenshot({ path: ".codex-tmp/calendar-access-expiry/mobile-en-day.png", fullPage: true });
  await mobile.close();
  console.log("Calendar expiry: day-only renewal, pending refresh, keyboard, English mobile, drag boundaries and permanent display passed");
} finally { await browser?.close(); await fixture.close(); }
